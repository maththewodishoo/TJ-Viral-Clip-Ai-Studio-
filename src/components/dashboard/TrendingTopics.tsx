import { Link } from "react-router-dom";
import { Flame, TrendingUp } from "lucide-react";
import { Badge, Panel, SectionHeader } from "@/components/ui/primitives";
import { useWorkspace } from "@/lib/store";

export function TrendingTopics() {
  const ws = useWorkspace();
  const topics = ws.trends.slice(0, 5);
  const allSample = topics.every((t) => t.source === "sample");

  return (
    <Panel className="flex h-full flex-col p-3.5">
      <SectionHeader
        icon={<Flame size={16} />}
        title="Trending Topics"
        right={
          <Link to="/trends" className="text-[10.5px] font-medium text-brand-300 hover:text-brand-200">
            View More →
          </Link>
        }
      />
      <div className="mt-1.5">
        {allSample ? (
          <Badge tone="sample">Illustrative sample data — no live trend source connected</Badge>
        ) : (
          <Badge tone="info">AI editorial ideas — not measured platform trends</Badge>
        )}
      </div>
      <ul className="mt-2 space-y-0.5">
        {topics.map((topic, i) => (
          <li key={topic.id} className="flex items-center gap-2 rounded-md px-0.5 py-1.5">
            <span className="grid h-5 w-5 shrink-0 place-items-center rounded-full border border-white/10 bg-white/[0.04] text-[9.5px] font-semibold text-[#b6aed6]">
              {i + 1}
            </span>
            <span className="min-w-0 flex-1 truncate text-[11.5px] text-[#d7d1ee]">{topic.topic}</span>
            <span className="flex items-center gap-0.5 text-[10.5px] font-semibold text-emerald-400">
              <TrendingUp size={11} />+{topic.growth}%{topic.source === "sample" && <span className="text-[8px] text-amber-300/80">*</span>}
            </span>
          </li>
        ))}
      </ul>
      <p className="mt-auto pt-2 text-[9px] leading-relaxed text-[#6f679a]">
        {allSample
          ? "* Sample figures for layout only. Connect a trend source to show measured growth."
          : "Generated by your configured AI provider. Percentages are confidence scores, not platform growth."}
      </p>
    </Panel>
  );
}
